#!/usr/bin/env bash
# Shared by build-nginx.sh and apply-nginx-conf.sh. Source this file; do not execute it.
# shellcheck shell=bash

NGINX_MARKER='Generated by scripts/nginx/'

#: Where nginx lives on every host. /root/local/nginx is a symlink to a versioned prefix,
#: so the path in a config file never changes when the version does. The two overrides
#: exist for tests; nobody should set them on a real host.
INSTALL_ROOT="${JC_NGINX_INSTALL_ROOT:-/root/local}"
SOFT_ROOT="${JC_NGINX_SOFT_ROOT:-/root/soft}"
NGINX_HOME="${INSTALL_ROOT}/nginx"
NGINX_BIN="${NGINX_HOME}/sbin/nginx"
CONF_DIR="${NGINX_HOME}/conf"
MAIN_CONF="${CONF_DIR}/nginx.conf"
SERVER_DIR="${CONF_DIR}/server"
SSL_DIR="${NGINX_HOME}/ssl"
LOG_DIR="${NGINX_HOME}/logs"

LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEMPLATE_DIR="${LIB_DIR}/templates"

log() { printf '[%s] %s\n' "${LOG_TAG:-jc-nginx}" "$*"; }
die() { printf '[%s] ERROR: %s\n' "${LOG_TAG:-jc-nginx}" "$*" >&2; exit 1; }

require_root() {
  [[ "$(id -u)" -eq 0 ]] || die "run as root (sudo $0)"
}

is_ipv4() {
  [[ "$1" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]
}

nginx_version_number() {
  local raw major minor patch
  raw="$("$NGINX_BIN" -v 2>&1 | sed -nE 's#.*nginx/([0-9]+)\.([0-9]+)\.([0-9]+).*#\1 \2 \3#p' | head -1)"
  [[ -n "$raw" ]] || { echo 9999999; return; }
  read -r major minor patch <<<"$raw"
  echo $((major * 1000000 + minor * 1000 + patch))
}

# nginx rewrites its process title to "nginx: master process <argv>", so the binary path it was
# started with shows up there. /root/local/nginx is a symlink and a service manager may have
# started the real path, so both spellings count.
nginx_is_running() {
  local real
  real="$(realpath "$NGINX_BIN" 2>/dev/null || echo "$NGINX_BIN")"
  pgrep -f "nginx: master process (${NGINX_BIN}|${real})( |$)" >/dev/null 2>&1
}

# True when the file is one this tooling wrote (any earlier generation of it).
is_generated_conf() {
  grep -q "$NGINX_MARKER" "$1" 2>/dev/null
}

is_stock_conf() {
  [[ -f "${1}.default" ]] && cmp -s "$1" "${1}.default"
}

# Substitutes every __JC_*__ placeholder. The values are validated before they get here:
# a `|` or newline in any of them would break the sed expression.
render_template() {
  local src="$1" dest="$2"
  sed \
    -e "s|__JC_NGINX_CONF__|${CONF_DIR}|g" \
    -e "s|__JC_NGINX_LOGS__|${LOG_DIR}|g" \
    -e "s|__JC_SERVER_DIR__|${SERVER_DIR}|g" \
    -e "s|__JC_SSL_DIR__|${SSL_DIR}|g" \
    -e "s|__JC_SERVER_NAME__|${SERVER_NAMES:-}|g" \
    -e "s|__JC_HTTPS_PORT__|${HTTPS_PORT:-443}|g" \
    -e "s|__JC_WEB_PORT__|${WEB_PORT:-3000}|g" \
    -e "s|__JC_API_PORT__|${API_PORT:-8000}|g" \
    -e "s|__JC_HTTP_LISTEN_FLAGS__|${HTTP_LISTEN_FLAGS:-}|g" \
    -e "s|__JC_HTTPS_LISTEN_FLAGS__|${HTTPS_LISTEN_FLAGS:-}|g" \
    -e "s|__JC_HTTP2_ON__|${HTTP2_ON_LINE:-}|g" \
    "$src" >"$dest"
}
