#!/usr/bin/env node
/**
 * Static checks, nothing is executed from the app: (1) every source file parses; (2) no innerHTML /
 * eval / document.write anywhere in src (content must reach the page as text); (3) every relative import
 * resolves to a file; (4) no direct storage / Audio / fetch outside the files that own them.
 */
import { readdirSync, readFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('..', import.meta.url));
const walk = d => readdirSync(d).flatMap(n => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
// kernel/ and platform-web/ under src/ are generated by build.mjs from student-app/runtime/. They are
// copies, not our source: platform-web legitimately owns Audio/storage/fetch (it *is* the platform layer),
// so scanning them would report the same file as both owner and offender. The originals live in
// student-app/runtime/ and are checked there.
const GENERATED = new Set(['kernel', 'platform-web']);
const walkSrc = d => readdirSync(d).flatMap(n => {
  const p = join(d, n);
  if (statSync(p).isDirectory()) return GENERATED.has(n) ? [] : walkSrc(p);
  return [p];
});
const files = walkSrc(join(root, 'src')).filter(f => f.endsWith('.js'));
let bad = 0;
const fail = m => { bad++; console.log(`  FAIL ${m}`); };

for (const f of files) {
  const r = spawnSync(process.execPath, ['--check', f], { encoding: 'utf8' });
  if (r.status !== 0) fail(`syntax ${relative(root, f)}\n${r.stderr}`);
}
const OWNS = { storage: ['platform.js', 'core/store.js'], audio: ['platform.js'], fetch: ['data/api.js', 'data/agent-client.js', 'character/mount.js', 'ui/media.js', 'main.js'] };
for (const f of files) {
  const rel = relative(join(root, 'src'), f);
  if (rel.startsWith('character/core.js')) continue;
  const text = readFileSync(f, 'utf8');
  if (/\.innerHTML\s*=|insertAdjacentHTML|document\.write|\beval\s*\(|new Function\(/.test(text)) fail(`unsafe HTML/eval in ${rel}`);
  for (const m of text.matchAll(/from\s+['"](\.[^'"]+)['"]/g)) {
    const target = resolve(dirname(f), m[1]);
    if (!existsSync(target)) fail(`unresolved import ${m[1]} in ${rel}`);
  }
  if (/\blocalStorage\b|\bsessionStorage\b/.test(text) && !OWNS.storage.includes(rel)) fail(`direct storage in ${rel}`);
  if (/new Audio\(/.test(text) && !OWNS.audio.includes(rel)) fail(`direct Audio in ${rel}`);
  if (/\bfetch\(/.test(text) && !OWNS.fetch.includes(rel)) fail(`direct fetch in ${rel}`);
}
console.log(bad ? `check: ${bad} problem(s)` : `check: ${files.length} files ok`);
process.exit(bad ? 1 : 0);
