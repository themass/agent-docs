#!/usr/bin/env bash
# Start TencentDB Agent Memory for Content Studio.
# Runtime modes:
#   source (default): MemoryCore + MemoryProxy as local Node processes, SQLite storage.
#   docker:           existing Docker deployment (opt-in compatibility mode).
set -euo pipefail

TDAI_RUNTIME="${TDAI_RUNTIME:-source}"
TDAI_MEMORY_DIR="${TDAI_MEMORY_DIR:-/Users/gqli/work/TencentDB-Agent-Memory}"
TDAI_CORE_DIR="${TDAI_CORE_DIR:-$TDAI_MEMORY_DIR/MemoryCore}"
TDAI_PROXY_DIR="${TDAI_PROXY_DIR:-$TDAI_MEMORY_DIR/MemoryProxy}"
DEPLOY="${TDAI_DEPLOY_DIR:-$TDAI_MEMORY_DIR/deploy/global-images}"
ENV_FILE="${TDAI_ENV_FILE:-$DEPLOY/.env}"
RUNTIME_DIR="${RUNTIME_DIR:?RUNTIME_DIR required}"
LOGS_DIR="${LOGS_DIR:-$RUNTIME_DIR/logs}"
MEMORY_CORE_PORT="${MEMORY_CORE_PORT:-8420}"
MEMORY_PANEL_PORT="${MEMORY_PANEL_PORT:-8125}"
MEMORY_KNOWLEDGE_PORT="${MEMORY_KNOWLEDGE_PORT:-8424}"
MEMORY_PROXY_PORT="${MEMORY_PROXY_PORT:-8096}"
OPENINSPECTOR_URL="${OPENINSPECTOR_URL:-http://127.0.0.1:8080}"
TDAI_LLM_BASE_URL="${TDAI_LLM_BASE_URL:-${OPENINSPECTOR_URL}/v1}"
TDAI_LLM_API_KEY="${TDAI_LLM_API_KEY:-}"
TDAI_LLM_MODEL="${TDAI_LLM_MODEL:-gpt-5-6-luna}"
TDAI_SPACE_ID="${TDAI_SPACE_ID:-default}"
TDAI_CORE_DATA_DIR="${TDAI_CORE_DATA_DIR:-$RUNTIME_DIR/tdai-memory/core}"
TDAI_PROXY_DB_PATH="${TDAI_PROXY_DB_PATH:-$RUNTIME_DIR/tdai-memory/proxy.db}"
TDAI_NODE="${TDAI_NODE:-}"

log() { printf '\033[1;36m[tdai-memory]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[tdai-memory]\033[0m %s\n' "$*"; }
err() { printf '\033[1;31m[tdai-memory]\033[0m %s\n' "$*" >&2; }
mkdir -p "$LOGS_DIR" "$RUNTIME_DIR" "$TDAI_CORE_DATA_DIR" "$(dirname "$TDAI_PROXY_DB_PATH")"

write_env() {
  local admin_key="${1:-}"
  {
    printf 'TDAI_RUNTIME=%q\n' "$TDAI_RUNTIME"
    printf 'TDAI_MEMORY_DIR=%q\n' "$TDAI_MEMORY_DIR"
    printf 'TDAI_PANEL_URL=%q\n' "http://127.0.0.1:${MEMORY_PANEL_PORT}"
    printf 'TDAI_CORE_URL=%q\n' "http://127.0.0.1:${MEMORY_CORE_PORT}"
    printf 'TDAI_KNOWLEDGE_URL=%q\n' "http://127.0.0.1:${MEMORY_KNOWLEDGE_PORT}"
    printf 'TDAI_PROXY_URL=%q\n' "http://127.0.0.1:${MEMORY_PROXY_PORT}"
    printf 'TDAI_SPACE_ID=%q\n' "$TDAI_SPACE_ID"
    printf 'TDAI_PROXY_HERMES_BASE=%q\n' "http://127.0.0.1:${MEMORY_PROXY_PORT}/hermes/${TDAI_SPACE_ID}"
    printf 'TDAI_PROXY_CODEX_BASE=%q\n' "http://127.0.0.1:${MEMORY_PROXY_PORT}/codex/${TDAI_SPACE_ID}"
    printf 'TDAI_PROXY_OPENAI_CHAT_BASE=%q\n' "http://127.0.0.1:${MEMORY_PROXY_PORT}/codebuddy/${TDAI_SPACE_ID}"
    [[ -n "$admin_key" ]] && printf 'TDAI_USER_KEY=%q\n' "$admin_key"
  } > "$RUNTIME_DIR/tdai-memory.env"
  chmod 600 "$RUNTIME_DIR/tdai-memory.env" 2>/dev/null || true
  printf '%s\n' "$TDAI_RUNTIME" > "$RUNTIME_DIR/tdai-memory-runtime"
}

wait_http() {
  local url="$1" label="$2" timeout="${3:-60}" i
  for ((i=0; i<timeout; i++)); do
    if curl -fsS -m 2 "$url" >/dev/null 2>&1; then log "$label ready: $url"; return 0; fi
    sleep 1
  done
  err "$label did not become ready: $url"
  return 1
}

port_up() { curl -fsS -m 2 "http://127.0.0.1:$1/health" >/dev/null 2>&1 || curl -fsS -m 2 "http://127.0.0.1:$1/" >/dev/null 2>&1; }

start_source() {
  if [[ -z "$TDAI_NODE" ]]; then
    if [[ -x /opt/homebrew/opt/node@22/bin/node ]]; then TDAI_NODE=/opt/homebrew/opt/node@22/bin/node
    elif [[ -x /usr/local/opt/node@22/bin/node ]]; then TDAI_NODE=/usr/local/opt/node@22/bin/node
    else TDAI_NODE="$(command -v node || true)"; fi
  fi
  [[ -x "$TDAI_NODE" ]] || { err "Node.js is required for TDAI_RUNTIME=source"; return 1; }
  local node_version node_major; node_version="$($TDAI_NODE --version)"; node_major="$($TDAI_NODE -p 'process.versions.node.split(".")[0]')"
  (( node_major == 22 )) || { err "MemoryProxy requires Node.js 22.x (found $node_version); install Node 22 or set TDAI_NODE"; return 1; }
  [[ -f "$TDAI_CORE_DIR/package.json" ]] || { err "Missing MemoryCore: $TDAI_CORE_DIR"; return 1; }
  [[ -f "$TDAI_PROXY_DIR/package.json" ]] || { err "Missing MemoryProxy: $TDAI_PROXY_DIR"; return 1; }
  [[ -d "$TDAI_CORE_DIR/node_modules" ]] || { err "Missing MemoryCore dependencies. Run: cd $TDAI_CORE_DIR && pnpm install"; return 1; }
  [[ -d "$TDAI_PROXY_DIR/node_modules" ]] || { err "Missing MemoryProxy dependencies. Run: cd $TDAI_PROXY_DIR && npm install"; return 1; }
  [[ -n "$TDAI_LLM_API_KEY" ]] || { err "TDAI_LLM_API_KEY empty — configure LLM_API_KEY in Hermes profile secrets"; return 1; }

  local core_config="$RUNTIME_DIR/tdai-gateway.standalone.yaml"
  cat > "$core_config" <<YAML
# Generated by start-tdai-memory.sh; do not edit the repository config.
deployMode: standalone
stateBackend: local
server:
  port: ${MEMORY_CORE_PORT}
  host: 127.0.0.1
data:
  baseDir: ${TDAI_CORE_DATA_DIR}
llm:
  baseUrl: ${TDAI_LLM_BASE_URL}
  apiKey: ${TDAI_LLM_API_KEY}
  model: ${TDAI_LLM_MODEL}
  maxTokens: 4096
  timeoutMs: 120000
memory:
  capture:
    enabled: true
  extraction:
    enabled: true
    enableDedup: true
    maxMemoriesPerSession: 20
  recall:
    enabled: true
    maxResults: 5
    scoreThreshold: 0.3
    strategy: hybrid
    timeoutMs: 5000
  storeBackend: sqlite
  embedding:
    provider: none
  bm25:
    enabled: true
    language: zh
YAML
  chmod 600 "$core_config" 2>/dev/null || true
  local proxy_config="$RUNTIME_DIR/tdai-proxy.yaml"
  cat > "$proxy_config" <<YAML
server:
  host: 127.0.0.1
  port: ${MEMORY_PROXY_PORT}
  forwardTimeoutMs: 600000
upstream:
  url: ${TDAI_LLM_BASE_URL}
  apiKey: ${TDAI_LLM_API_KEY}
redis:
  enabled: false
storage:
  enabled: true
  backend: sqlite
  ttlDays: 7
  sqlite:
    dbPath: ${TDAI_PROXY_DB_PATH}
injection:
  enabled: true
  injectors:
    - tdai-memory
tdai:
  enabled: true
  endpoint: http://127.0.0.1:${MEMORY_CORE_PORT}
  apiKey: local
  serviceId: default
  memory:
    enabled: true
    inject: true
    writeL0: true
    recallL1: true
    injectL2L3: true
YAML
  chmod 600 "$proxy_config" 2>/dev/null || true
  if port_up "$MEMORY_CORE_PORT"; then log "MemoryCore already listening on :$MEMORY_CORE_PORT"; else
    log "Starting MemoryCore source on :$MEMORY_CORE_PORT"
    (cd "$TDAI_CORE_DIR" && nohup env TDAI_GATEWAY_CONFIG="$core_config" TDAI_LLM_BASE_URL="$TDAI_LLM_BASE_URL" TDAI_LLM_API_KEY="$TDAI_LLM_API_KEY" TDAI_LLM_MODEL="$TDAI_LLM_MODEL" TDAI_GATEWAY_PORT="$MEMORY_CORE_PORT" TDAI_GATEWAY_HOST=127.0.0.1 "$TDAI_NODE" --import tsx src/gateway/server.ts >>"$LOGS_DIR/memory-core.log" 2>&1 & echo $! > "$RUNTIME_DIR/memory-core.pid")
  fi
  wait_http "http://127.0.0.1:${MEMORY_CORE_PORT}/health" "MemoryCore" 60 || return 1
  if port_up "$MEMORY_PROXY_PORT"; then log "MemoryProxy already listening on :$MEMORY_PROXY_PORT"; else
    log "Starting MemoryProxy source on :$MEMORY_PROXY_PORT"
    (cd "$TDAI_PROXY_DIR" && nohup env "$TDAI_NODE" --import tsx/esm src/index.ts --config "$proxy_config" >>"$LOGS_DIR/memory-proxy.log" 2>&1 & echo $! > "$RUNTIME_DIR/memory-proxy.pid")
  fi
  wait_http "http://127.0.0.1:${MEMORY_PROXY_PORT}/health" "MemoryProxy" 60 || return 1
  write_env local
}

start_docker() {
  [[ -d "$DEPLOY" ]] || { err "Missing Docker deployment: $DEPLOY"; return 1; }
  command -v docker >/dev/null 2>&1 || { err "docker not found for TDAI_RUNTIME=docker"; return 1; }
  [[ -n "$TDAI_LLM_API_KEY" ]] || { err "TDAI_LLM_API_KEY empty"; return 1; }
  [[ -f "$ENV_FILE" ]] || cp "$DEPLOY/.env.example" "$ENV_FILE"
  export MEMORY_CORE_PORT MEMORY_PANEL_PORT MEMORY_KNOWLEDGE_PORT MEMORY_PROXY_PORT TDAI_LLM_API_KEY TDAI_LLM_MODEL
  TDAI_DOCKER_UPSTREAM_URL="${TDAI_LLM_BASE_URL/127.0.0.1/host.docker.internal}"
  TDAI_DOCKER_UPSTREAM_URL="${TDAI_DOCKER_UPSTREAM_URL/localhost/host.docker.internal}"
  export TDAI_DOCKER_UPSTREAM_URL
  python3 - "$ENV_FILE" <<'PY'
import os,re,sys
p=sys.argv[1]; text=open(p,encoding='utf-8').read()
vals={'MEMORY_CORE_PORT':os.environ['MEMORY_CORE_PORT'],'PANEL_PORT':os.environ['MEMORY_PANEL_PORT'],'KNOWLEDGE_PORT':os.environ['MEMORY_KNOWLEDGE_PORT'],'PROXY_PORT':os.environ['MEMORY_PROXY_PORT'],'MEMORY_LLM_BASE_URL':os.environ['TDAI_DOCKER_UPSTREAM_URL'],'MEMORY_LLM_API_KEY':os.environ['TDAI_LLM_API_KEY'],'MEMORY_LLM_MODEL':os.environ['TDAI_LLM_MODEL'],'MEMORY_LLM_PROTOCOL':'openai','PROXY_UPSTREAM_URL':os.environ['TDAI_DOCKER_UPSTREAM_URL'],'PROXY_UPSTREAM_API_KEY':os.environ['TDAI_LLM_API_KEY'],'PROXY_UPSTREAM_MODEL':os.environ['TDAI_LLM_MODEL'],'MEMORY_CORE_GATEWAY_API_KEY':''}
for k,v in vals.items():
 line=f'{k}={v}'; pat=re.compile(rf'^{re.escape(k)}=.*$',re.M); text=pat.sub(line,text,count=1) if pat.search(text) else text.rstrip()+"\\n"+line+"\\n"
open(p,'w',encoding='utf-8').write(text)
PY
  { echo "=== $(date -Iseconds) tdai-memory docker start ==="; cd "$DEPLOY"; export ENV_FILE; PROXY_FULL_STACK="${PROXY_FULL_STACK:-1}" ./start-memory-core.sh; PROXY_FULL_STACK="${PROXY_FULL_STACK:-1}" ./start-memory-hub.sh; PROXY_FULL_STACK="${PROXY_FULL_STACK:-1}" ./start-proxy.sh; } >>"$LOGS_DIR/tdai-memory.log" 2>&1
  write_env "$(tr -d ' \n\r' < "$DEPLOY/.admin-key" 2>/dev/null || true)"
}

case "$TDAI_RUNTIME" in
  source) start_source;;
  docker) start_docker;;
  *) err "Unknown TDAI_RUNTIME=$TDAI_RUNTIME (use source|docker)"; exit 2;;
esac
